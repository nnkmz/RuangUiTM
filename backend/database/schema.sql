CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('admin','manager','viewer') NOT NULL DEFAULT 'viewer',
 active BOOLEAN NOT NULL DEFAULT TRUE,
 auth_version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS campuses (
 code VARCHAR(32) PRIMARY KEY, name VARCHAR(150) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS buildings (
 code VARCHAR(32) PRIMARY KEY, campus_code VARCHAR(32) NOT NULL,
 name VARCHAR(150) NOT NULL,
 FOREIGN KEY(campus_code) REFERENCES campuses(code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS floors (
 building_code VARCHAR(32) NOT NULL, code VARCHAR(32) NOT NULL,
 name VARCHAR(120) NOT NULL,
 width_m DECIMAL(10,3) NOT NULL DEFAULT 42, height_m DECIMAL(10,3) NOT NULL DEFAULT 21,
 PRIMARY KEY(building_code,code),
 FOREIGN KEY(building_code) REFERENCES buildings(code),
 CHECK(width_m > 0 AND height_m > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rooms (
 id VARCHAR(100) PRIMARY KEY,
 building_code VARCHAR(32) NOT NULL, floor_code VARCHAR(32) NOT NULL,
 room_code VARCHAR(64) NOT NULL, name VARCHAR(150) NOT NULL,
 room_type VARCHAR(64) NOT NULL, category VARCHAR(32) NOT NULL,
 department VARCHAR(100) NOT NULL,
 area_polygon DECIMAL(12,4) NULL, area_manual DECIMAL(12,4) NOT NULL DEFAULT 0,
 capacity INT UNSIGNED NOT NULL DEFAULT 0, occupants INT UNSIGNED NOT NULL DEFAULT 0,
 status VARCHAR(32) NOT NULL, polygon JSON NULL, attributes JSON NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 archived_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY room_location_code(building_code,floor_code,room_code),
 KEY room_filter(building_code,floor_code,archived_at),
 FOREIGN KEY(building_code,floor_code) REFERENCES floors(building_code,code),
 CHECK(area_manual >= 0), CHECK(area_polygon IS NULL OR area_polygon > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 actor_id BIGINT UNSIGNED NULL, action VARCHAR(50) NOT NULL,
 entity_type VARCHAR(32) NOT NULL, entity_id VARCHAR(100) NOT NULL,
 before_data JSON NULL, after_data JSON NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY audit_entity(entity_type,entity_id),
 FOREIGN KEY(actor_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS login_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 fingerprint CHAR(64) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY attempt_window(fingerprint,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS migrations (
 version VARCHAR(100) PRIMARY KEY, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
